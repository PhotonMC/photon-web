// Writes the website's CSS skins and the client's Rust token module from design/tokens.json.
// Run: bun scripts/gen-tokens.mjs   (the Rust file is committed in the client repository).
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));
const rustOut = process.env.PHOTON_CLIENT_TOKENS ?? resolve(root, "../voxel-client/crates/photon-gui/src/tokens.rs");

const check = process.argv.includes("--check");
const kebab = (s) => s.replaceAll("_", "-");
const selector = { light: ":root", dark: ".dark", classic: '[data-skin="classic"]' };

function rgba(hex) {
  const m = /^#([0-9a-f]{6})([0-9a-f]{2})?$/i.exec(hex);
  if (!m) throw new Error(`bad color ${hex}`);
  return (parseInt(m[2] ?? "ff", 16) << 24 | parseInt(m[1], 16)) >>> 0;
}

let css = "/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */\n";
for (const [skin, colors] of Object.entries(tokens.skins)) {
  const shape = tokens.shape[skin];
  css += `\n${selector[skin]} {\n`;
  for (const [k, v] of Object.entries(colors)) css += `  --${kebab(k)}: ${v};\n`;
  css += `  --radius-ui: ${shape.radius}px;\n  --border-ui: ${shape.border}px;\n  --offset-ui: ${shape.offset}px;\n  --space-ui: ${shape.space}px;\n`;
  css += `  --font-ui: var(--font-${shape.font});\n`;
  css += `  color-scheme: ${skin === "light" ? "light" : "dark"};\n}\n`;
}
const out = (path, text) => {
  if (check) {
    let cur = "";
    try { cur = readFileSync(path, "utf8"); } catch {}
    if (cur !== text) { console.error(`stale: ${path}; run bun scripts/gen-tokens.mjs`); process.exitCode = 1; }
  } else writeFileSync(path, text);
};
out(resolve(root, "app/tokens.css"), css);

const names = Object.keys(tokens.skins.light);
let rs = "//! Design tokens of the Photon skins, as 0xAARRGGBB colors.\n//!\n";
rs += "//! Generated by `photon-web/scripts/gen-tokens.mjs` from `design/tokens.json`. Do not edit.\n\n";
rs += "/// One skin's colors and shape.\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub struct Skin {\n";
for (const n of names) rs += `    pub ${n}: u32,\n`;
rs += "    pub radius: u32,\n    pub border: u32,\n    pub offset: u32,\n    pub space: u32,\n}\n";
for (const [skin, colors] of Object.entries(tokens.skins)) {
  const shape = tokens.shape[skin];
  rs += `\npub const ${skin.toUpperCase()}: Skin = Skin {\n`;
  for (const n of names) rs += `    ${n}: 0x${rgba(colors[n]).toString(16).padStart(8, "0").toUpperCase()},\n`;
  rs += `    radius: ${shape.radius},\n    border: ${shape.border},\n    offset: ${shape.offset},\n    space: ${shape.space},\n};\n`;
}
const all = Object.keys(tokens.skins).map((k) => `("${k}", ${k.toUpperCase()})`).join(", ");
rs += `\n/// Every skin with its name.\npub const ALL: [(&str, Skin); ${Object.keys(tokens.skins).length}] = [${all}];\n`;
if (!check) {
  writeFileSync(rustOut, rs);
  execFileSync("rustfmt", ["--edition", "2024", rustOut]);
  console.log(`wrote app/tokens.css and ${rustOut}`);
} else {
  const tmp = rustOut + ".check";
  writeFileSync(tmp, rs);
  execFileSync("rustfmt", ["--edition", "2024", tmp]);
  out(rustOut, readFileSync(tmp, "utf8"));
  execFileSync("rm", [tmp]);
}
